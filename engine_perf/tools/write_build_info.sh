#!/usr/bin/env bash
# Writes the identity EnginePerfInfo reports (lib/ui/engine_perf/engine_perf_ffi.cc)
# into engine/src/flutter/lib/ui/engine_perf/engine_perf_build_info.h (not checked in):
#   engine_perf/tools/write_build_info.sh [<patch set>]      # ext.<n>; "dev" by default
# Run from anywhere inside this checkout, before building.
set -euo pipefail
patch_set="${1:-${ENGINE_PERF_PATCH_SET:-dev}}"
root="$(git rev-parse --show-toplevel)"
cd "$root"
# The Flutter release the patches sit on: the newest x.y.z tag reachable.
flutter_version="${ENGINE_PERF_FLUTTER_VERSION:-$(git describe --tags --abbrev=0 --match '[0-9]*.[0-9]*.[0-9]*' HEAD 2>/dev/null || echo dev)}"
cat >"engine/src/flutter/lib/ui/engine_perf/engine_perf_build_info.h" <<H
// Generated by engine_perf/tools/write_build_info.sh; not checked in.
#define ENGINE_PERF_FLUTTER_VERSION "$flutter_version"
#define ENGINE_PERF_ENGINE_REVISION "$(cat bin/internal/engine.version)"
#define ENGINE_PERF_PATCH_SET "$patch_set"
#define ENGINE_PERF_FORK_COMMIT "$(git rev-parse HEAD)"
H
echo "write_build_info: Flutter $flutter_version, patch set $patch_set"
